#!/usr/bin/env python3
"""Generate the DEVELOPMENT FIDO attestation key and self-signed certificate.

The key is committed to the repository, so it is public: attestation from a dongle using it
proves nothing. It only exists so canokey-core can produce "packed" attestation during
development. Production devices must use a per-device key (see local/fido-spike.md).

    tools/.venv/Scripts/python tools/gen_dev_attestation.py
"""

import datetime
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import NameOID

OUT = Path(__file__).resolve().parent.parent / "components" / "canokey" / "port" / "dev_attestation.c"


def c_array(data):
    lines = []
    for i in range(0, len(data), 12):
        lines.append("    " + " ".join(f"0x{b:02x}," for b in data[i:i + 12]))
    return "\n".join(lines)


def main():
    key = ec.generate_private_key(ec.SECP256R1())
    name = x509.Name([
        x509.NameAttribute(NameOID.COUNTRY_NAME, "AR"),
        x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Keyling"),
        x509.NameAttribute(NameOID.ORGANIZATIONAL_UNIT_NAME, "Authenticator Attestation"),
        x509.NameAttribute(NameOID.COMMON_NAME, "Keyling Development Attestation"),
    ])
    now = datetime.datetime(2026, 1, 1, tzinfo=datetime.timezone.utc)
    cert = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(name)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now)
        .not_valid_after(now + datetime.timedelta(days=365 * 20))
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        .sign(key, hashes.SHA256())
    )
    priv = key.private_numbers().private_value.to_bytes(32, "big")
    der = cert.public_bytes(serialization.Encoding.DER)

    OUT.write_text(
        "/* Generated by tools/gen_dev_attestation.py. DEVELOPMENT ONLY: this key is public. */\n"
        "#include <stddef.h>\n#include <stdint.h>\n\n"
        f"const uint8_t canokey_dev_attestation_key[32] = {{\n{c_array(priv)}\n}};\n\n"
        f"const uint8_t canokey_dev_attestation_cert[] = {{\n{c_array(der)}\n}};\n\n"
        "const size_t canokey_dev_attestation_cert_len = sizeof(canokey_dev_attestation_cert);\n",
        newline="\n",
    )
    print(f"wrote {OUT} (cert {len(der)} bytes)")


if __name__ == "__main__":
    main()
