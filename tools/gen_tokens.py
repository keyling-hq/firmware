#!/usr/bin/env python3
"""Regenerate the C constants for the design tokens in design/tokens/ (keyling-hq/design).

    tools/.venv/Scripts/python tools/gen_tokens.py
    tools/.venv/Scripts/python tools/gen_tokens.py --check

Writes components/ui/ui_tokens.h (Candy: palette, app colors, radii) from candy.json and
components/status_led/status_led_tokens.h (the LED's colors) from led.json. --check fails if either
is out of date, for CI. Fonts are listed in the tokens for the hub; the firmware bundles its own.
"""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens"
HEADER = "/* Generated by tools/gen_tokens.py from design/tokens/{source}. Do not edit. */\n#pragma once\n\n"


def macro(*parts: str) -> str:
    return "_".join(re.sub(r"[^A-Za-z0-9]+", "_", p).upper() for p in parts)


def color(token: dict) -> str:
    value = token["$value"]
    if not re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
        raise SystemExit(f"not an sRGB hex color: {value}")
    return "0x" + value[1:].upper()


def tokens(node: dict) -> list[tuple[str, dict]]:
    """The tokens directly in a group, in file order: entries with a $value."""
    return [(name, t) for name, t in node.items() if not name.startswith("$") and "$value" in t]


def px(token: dict) -> str:
    value = token["$value"]
    if not value.endswith("px"):
        raise SystemExit(f"not a px dimension: {value}")
    return value[:-2]


def defines(rows: list[tuple[str, str]]) -> str:
    return "".join(f"#define {name:<36}{value}\n" for name, value in rows)


def load(name: str) -> dict:
    return json.loads((TOKENS / name).read_text(encoding="utf-8"))


def render() -> dict[Path, str]:
    candy, led = load("candy.json"), load("led.json")
    palette = [(macro("UI_TOKEN_CANDY", name), color(t)) for name, t in tokens(candy["color"])]
    apps = [color(t) for _, t in tokens(candy["color"]["app"])]
    radii = [(macro("UI_TOKEN_RADIUS", name), px(t)) for name, t in tokens(candy["radius"])]
    radii.append(("UI_TOKEN_TILE_RADIUS_RATIO", f"{candy['tile-radius-ratio']['$value']}f"))
    leds = [(macro("STATUS_LED_TOKEN", name), color(t)) for name, t in tokens(led["color"])]
    return {
        ROOT / "components" / "ui" / "ui_tokens.h": HEADER.format(source="candy.json")
        + "/* Candy */\n"
        + defines(palette)
        + "\n/* App colors: Settings takes the first, the other apps the rest in launcher order */\n"
        + f"#define UI_TOKEN_CANDY_APP_COLORS           {{ {', '.join(apps)} }}\n"
        + "\n/* Radii in px; tiles round off by a share of their size */\n"
        + defines(radii),
        ROOT / "components" / "status_led" / "status_led_tokens.h": HEADER.format(source="led.json")
        + "/* Colors at full brightness, 0xRRGGBB */\n"
        + defines(leds),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Regenerate the C constants for the design tokens.")
    parser.add_argument("--check", action="store_true", help="fail if a generated header is out of date")
    args = parser.parse_args()
    outputs = render()
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        if stale:
            names = ", ".join(str(p.relative_to(ROOT)) for p in stale)
            raise SystemExit(f"out of date, run tools/gen_tokens.py: {names}")
        print("up to date")
        return
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
